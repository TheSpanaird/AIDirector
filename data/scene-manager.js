/**
 * EN-17 SECTOR REGENERATION ORCHESTRATION METHOD
 */
export async function executeSectorRegeneration({
  sectorId,
  manualGuidance = "",
  mode = "CONTENT_AND_PROMPTS",
  forcePrompts = false
}) {
  const manifest = DungeonLedgerManager.getActiveManifest();

  if (!manifest) {
    ui.notifications.error("AI Director | No active manifest found.");
    return null;
  }

  const result = await SectorRegenerationManager.regenerateSector({
    manifest,
    sectorId,
    mode,
    forcePrompts,
    manualGuidance,
    contentGenerator: generateLocalSectorContent
  });

  if (!result.success) {
    console.error("AI Director | EN-17 validation failed.", result.validation);
    ui.notifications.error("AI Director | Sector regeneration failed.");
    return result;
  }

  await DungeonLedgerManager.replaceActiveManifest(result.manifest);
  await updateExistingSceneManifest(result.manifest);

  ui.notifications.info(`AI Director | Regenerated ${result.sector.name}`);

  return result;
}

