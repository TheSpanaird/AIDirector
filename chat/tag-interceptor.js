// modules/ai-director/scripts/chat/tag-interceptor.js

import { compileNarrativeEvent } from "../ai/journal-compiler.js";
import { FactionManager } from "../simulation/faction-manager.js";
import { StateManager } from "../ai/state-manager.js";
import { updateActorSocialState } from "../ai/status-updater.js";

/**
 * Intercepts, parses, and executes database logic for AI Director plot hooks, 
 * emergent factions, and trust updates. Cleanses markup for player display.
 */
export const TagInterceptor = {
  /**
   * Parses raw AI output strings, extracts behavioral/world state tags,
   * executes their side-effects, and cleanses the markup for player display.
   */
  async processOutputTags(rawContent, actor = null) {
    if (!rawContent) return "";
    let sanitizedText = rawContent;
    const actorName = actor ? actor.name : "Unknown Source";

    // =======================================================================
    // 1. TRUST TAG EXTRACTION & STATE UPDATE
    // =======================================================================
    // 🛠️ REGEX UPDATED: Now optionally supports reason attributes if generated by LLM
    const trustRegex = /<trust-update\s+value=["'](-?\d+)["'](?:\s+reason=["']([^"']+)["'])?\s*\/?>/gi;
    let trustMatch;
    
    while ((trustMatch = trustRegex.exec(rawContent)) !== null) {
      if (actor) {
        const delta = parseInt(trustMatch[1], 10);
        const reason = trustMatch[2] ? trustMatch[2].trim() : "Narrative alignment shift."; // Fallback descriptive log
        
        if (delta !== 0) {
          // 🛠️ GAP CLOSED: Routed directly to updateActorSocialState to compile and write history logs!
          await updateActorSocialState(actor, delta, reason);
          ui.notifications.info(`AI Director: ${actorName} relationship shifted by ${delta}.`);
        }
      }
      sanitizedText = sanitizedText.replace(trustMatch[0], "");
    }

    // =======================================================================
    // 2. PLOT HOOK UNLOCKS (<trigger-hook id="id" />)
    // =======================================================================
    const hookRegex = /<trigger-hook\s+id=["']([^"']+)["']\s*\/?>/gi;
    const hookMatches = [...rawContent.matchAll(hookRegex)];
    const triggeredHooks = [];

    for (const match of hookMatches) {
      const hookId = match[1]?.trim();
      if (hookId && !triggeredHooks.includes(hookId)) {
        triggeredHooks.push(hookId);
        sanitizedText = sanitizedText.replace(match[0], "");

        ui.notifications.info(`AI Director | Narrative Event: Secret Plot Hook Unlocked [${hookId}]`);
        
        try {
          // Commit plot hook tracking log straight to the system db journal archives
          await compileNarrativeEvent(hookId, actorName);
        } catch (err) {
          console.error(`AI Director | Failed to compile journal event for hook: ${hookId}`, err);
        }
      }
    }

    // =======================================================================
    // 3. EMERGENT FACTION MATERIALIZATION & REGISTER (<create-faction />)
    // =======================================================================
    // ✅ NEW: Regex parsing engine to catch LLM-generated uncharted factions
    const factionCreateRegex = /<create-faction\s+id=["']([^"']+)["']\s+name=["']([^"']+)["']\s+tier=["']([^"']+)["']\s+description=["']([^"']+)["']\s*\/?>/gi;
    let factionCreateMatch;

    while ((factionCreateMatch = factionCreateRegex.exec(rawContent)) !== null) {
      const fId = factionCreateMatch[1]?.trim();
      const fName = factionCreateMatch[2]?.trim();
      const fTier = factionCreateMatch[3]?.trim() || "minor";
      const fDesc = factionCreateMatch[4]?.trim() || "";

      if (fId && fName) {
        try {
          // Register the new corporate/political player securely on the GM's thread
          await FactionManager.registerFaction(fId, fName, {
            tier: fTier,
            description: fDesc
          });
        } catch (err) {
          console.error(`AI Director | Error registering emergent faction via TagInterceptor:`, err);
        }
      }
      // Strip the raw tag cleanly to prevent it from bleeding into player chat templates
      sanitizedText = sanitizedText.replace(factionCreateMatch[0], "");
    }

    // =======================================================================
    // 4. FACTION PERMISSION REALIGNMENT (Moved down to maintain numerical order)
    // =======================================================================
    const factionJournal = game.journal.contents.find(
      j => j.name?.toLowerCase().includes("emergent faction") || j.getFlag("ai-director", "hookId")
    );

    if (factionJournal && triggeredHooks.includes(factionJournal.getFlag("ai-director", "hookId"))) {
      try {
        await factionJournal.update({
          "ownership.default": CONST.DOCUMENT_OWNERSHIP_LEVELS.OBSERVER
        });

        const firstPage = factionJournal.pages.contents[0];
        const pageText = firstPage?.text?.content || "";
        const factionFlagRegex = /\[Faction:\s*([^\s\]]+)\s+Shift:\s*([+-]?\d+)\]/gi;
        let factionMatch;
        
        while ((factionMatch = factionFlagRegex.exec(pageText)) !== null) {
          const factionId = factionMatch[1]?.trim();
          const shiftValue = parseInt(factionMatch[2], 10);
          
          if (factionId && !isNaN(shiftValue)) {
            await FactionManager.adjustFactionMetrics(factionId, { influence: shiftValue });
          }
        }

        Hooks.callAll("aiDirectorPlotHookUnlocked", factionJournal);
      } catch (error) {
        console.error(`AI Director | TagInterceptor Error adjusting faction journal permission matrix:`, error);
      }
    }

    return sanitizedText.trim();
  }
};