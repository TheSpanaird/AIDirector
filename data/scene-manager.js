/**
 * Cleans over-escaped JSON string artifacts and strips markdown fences generated by LLMs.
 * @param {string} rawString
 * @returns {string}
 */
export function sanitizeLLMJson(rawString) {
  if (!rawString) return "";
  let cleaned = rawString.trim();

  // Strip Markdown code fences
  cleaned = cleaned.replace(/^```json\s*/i, "").replace(/^```\s*/i, "").replace(/\s*```$/, "");

  // Fix over-escaped quotes and brackets
  return cleaned
    .replace(/\\"/g, '"')
    .replace(/\\\{/g, '{')
    .replace(/\\\}/g, '}')
    .replace(/\\\[/g, '[')
    .replace(/\\\]/g, ']');
}

/**
 * Native helper to extract the most recent text page content inside a named folder.
 * @param {string} folderName
 * @returns {string}
 */
export function getLatestJournalText(folderName) {
  const folder = game.folders.contents.find(f => f.name === folderName && f.type === "JournalEntry");
  if (!folder) return "";
  const entries = game.journal.contents
    .filter(j => j.folder?.id === folder.id)
    .sort((a, b) => b._stats.createdTime - a._stats.createdTime);
  if (!entries.length) return "";
  return entries[0].pages?.contents.filter(p => p.type === "text").map(p => p.text?.content || "").join("\n") || "";
}

